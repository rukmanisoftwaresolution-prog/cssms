-- CSSMS full schema + reference data (PostgreSQL) = Flyway V1__init_schema + V2__reference_data.
-- Run inside an EMPTY "cssms" database (after backend/db/create-database.sql), e.g.
--   psql -U postgres -d cssms -f cssms-schema.sql
-- The admin user is not created here; the backend creates it on first start.
-- If you run this script manually, start the backend with:
--   SPRING_FLYWAY_BASELINE_ON_MIGRATE=true  SPRING_FLYWAY_BASELINE_VERSION=2
-- (or skip this file and let Flyway build the schema from an empty database).

CREATE SEQUENCE seq_employee START 1;
CREATE SEQUENCE seq_supplier START 1;
CREATE SEQUENCE seq_customer START 1;
CREATE SEQUENCE seq_material START 1;
CREATE SEQUENCE seq_purchase_order START 1;
CREATE SEQUENCE seq_sales_order START 1;

CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(30)  NOT NULL UNIQUE,
    description VARCHAR(200)
);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    mobile_number VARCHAR(15),
    role_id       BIGINT       NOT NULL REFERENCES roles (id),
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP,
    created_by    VARCHAR(100),
    updated_by    VARCHAR(100),
    deleted       BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uq_users_username ON users (lower(username)) WHERE deleted = FALSE;
CREATE UNIQUE INDEX uq_users_email ON users (lower(email)) WHERE deleted = FALSE;

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id),
    token_hash VARCHAR(64)  NOT NULL UNIQUE,
    expires_at TIMESTAMP    NOT NULL,
    revoked    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);

CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP   NOT NULL,
    used       BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP   NOT NULL DEFAULT now()
);

CREATE TABLE employees (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code VARCHAR(20)    NOT NULL,
    full_name     VARCHAR(120)   NOT NULL,
    mobile_number VARCHAR(15)    NOT NULL,
    email         VARCHAR(150),
    address       VARCHAR(500),
    joining_date  DATE           NOT NULL,
    salary        NUMERIC(14, 2) NOT NULL DEFAULT 0,
    designation   VARCHAR(100),
    status        VARCHAR(15)    NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP,
    created_by    VARCHAR(100),
    updated_by    VARCHAR(100),
    deleted       BOOLEAN        NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uq_employees_code ON employees (employee_code);

CREATE TABLE suppliers (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_code  VARCHAR(20)  NOT NULL,
    supplier_name  VARCHAR(150) NOT NULL,
    gst_number     VARCHAR(15),
    pan_number     VARCHAR(10),
    contact_person VARCHAR(120) NOT NULL,
    mobile_number  VARCHAR(15)  NOT NULL,
    address        VARCHAR(500) NOT NULL,
    bank_details   VARCHAR(500),
    status         VARCHAR(15)  NOT NULL DEFAULT 'ACTIVE',
    created_at     TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at     TIMESTAMP,
    created_by     VARCHAR(100),
    updated_by     VARCHAR(100),
    deleted        BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uq_suppliers_code ON suppliers (supplier_code);
CREATE INDEX idx_suppliers_name ON suppliers (lower(supplier_name));

CREATE TABLE customers (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code      VARCHAR(20)    NOT NULL,
    customer_name      VARCHAR(150)   NOT NULL,
    company_name       VARCHAR(150),
    gst_number         VARCHAR(15),
    mobile_number      VARCHAR(15)    NOT NULL,
    email              VARCHAR(150),
    address            VARCHAR(500)   NOT NULL,
    credit_limit       NUMERIC(14, 2) NOT NULL DEFAULT 0,
    outstanding_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    status             VARCHAR(15)    NOT NULL DEFAULT 'ACTIVE',
    created_at         TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at         TIMESTAMP,
    created_by         VARCHAR(100),
    updated_by         VARCHAR(100),
    deleted            BOOLEAN        NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uq_customers_code ON customers (customer_code);
CREATE INDEX idx_customers_name ON customers (lower(customer_name));

CREATE TABLE materials (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_code VARCHAR(20)  NOT NULL,
    material_name VARCHAR(100) NOT NULL,
    description   VARCHAR(500),
    unit          VARCHAR(20)  NOT NULL DEFAULT 'TON',
    created_at    TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP,
    created_by    VARCHAR(100),
    updated_by    VARCHAR(100),
    deleted       BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uq_materials_code ON materials (material_code);
CREATE UNIQUE INDEX uq_materials_name ON materials (lower(material_name)) WHERE deleted = FALSE;

CREATE TABLE inventory (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id     BIGINT         NOT NULL UNIQUE REFERENCES materials (id),
    purchased_stock NUMERIC(14, 3) NOT NULL DEFAULT 0,
    sold_stock      NUMERIC(14, 3) NOT NULL DEFAULT 0,
    current_stock   NUMERIC(14, 3) NOT NULL DEFAULT 0,
    created_at      TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at      TIMESTAMP,
    created_by      VARCHAR(100),
    updated_by      VARCHAR(100),
    deleted         BOOLEAN        NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_inventory_non_negative CHECK (current_stock >= 0)
);

CREATE TABLE purchase_orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number      VARCHAR(30)    NOT NULL,
    po_date        DATE           NOT NULL,
    supplier_id    BIGINT         NOT NULL REFERENCES suppliers (id),
    vehicle_number VARCHAR(20),
    amount         NUMERIC(14, 2) NOT NULL DEFAULT 0,
    gst_amount     NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total_amount   NUMERIC(14, 2) NOT NULL DEFAULT 0,
    paid_amount    NUMERIC(14, 2) NOT NULL DEFAULT 0,
    payment_status VARCHAR(15)    NOT NULL DEFAULT 'PENDING',
    status         VARCHAR(15)    NOT NULL DEFAULT 'ACTIVE',
    cancel_reason  VARCHAR(500),
    remarks        VARCHAR(500),
    created_at     TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at     TIMESTAMP,
    created_by     VARCHAR(100),
    updated_by     VARCHAR(100),
    deleted        BOOLEAN        NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uq_po_number ON purchase_orders (po_number);
CREATE INDEX idx_po_supplier ON purchase_orders (supplier_id);
CREATE INDEX idx_po_date ON purchase_orders (po_date);

CREATE TABLE purchase_order_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT         NOT NULL REFERENCES purchase_orders (id),
    material_id       BIGINT         NOT NULL REFERENCES materials (id),
    quantity          NUMERIC(14, 3) NOT NULL,
    rate_per_ton      NUMERIC(14, 2) NOT NULL,
    gst_percentage    NUMERIC(5, 2)  NOT NULL DEFAULT 0,
    amount            NUMERIC(14, 2) NOT NULL,
    gst_amount        NUMERIC(14, 2) NOT NULL,
    total_amount      NUMERIC(14, 2) NOT NULL
);
CREATE INDEX idx_poi_po ON purchase_order_items (purchase_order_id);
CREATE INDEX idx_poi_material ON purchase_order_items (material_id);

CREATE TABLE sales_orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_number VARCHAR(30)  NOT NULL,
    invoice_number   VARCHAR(30)    NOT NULL,
    order_date       DATE           NOT NULL,
    customer_id      BIGINT         NOT NULL REFERENCES customers (id),
    delivery_address VARCHAR(500),
    vehicle_number   VARCHAR(20),
    sub_total        NUMERIC(14, 2) NOT NULL DEFAULT 0,
    discount_total   NUMERIC(14, 2) NOT NULL DEFAULT 0,
    gst_amount       NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total_amount     NUMERIC(14, 2) NOT NULL DEFAULT 0,
    advance_amount   NUMERIC(14, 2) NOT NULL DEFAULT 0,
    received_amount  NUMERIC(14, 2) NOT NULL DEFAULT 0,
    pending_amount   NUMERIC(14, 2) NOT NULL DEFAULT 0,
    payment_status   VARCHAR(15)    NOT NULL DEFAULT 'PENDING',
    status           VARCHAR(15)    NOT NULL DEFAULT 'ACTIVE',
    cancel_reason    VARCHAR(500),
    remarks          VARCHAR(500),
    created_at       TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at       TIMESTAMP,
    created_by       VARCHAR(100),
    updated_by       VARCHAR(100),
    deleted          BOOLEAN        NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uq_so_number ON sales_orders (sales_order_number);
CREATE UNIQUE INDEX uq_so_invoice ON sales_orders (invoice_number);
CREATE INDEX idx_so_customer ON sales_orders (customer_id);
CREATE INDEX idx_so_date ON sales_orders (order_date);

CREATE TABLE sales_order_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id BIGINT         NOT NULL REFERENCES sales_orders (id),
    material_id    BIGINT         NOT NULL REFERENCES materials (id),
    quantity       NUMERIC(14, 3) NOT NULL,
    rate           NUMERIC(14, 2) NOT NULL,
    discount       NUMERIC(14, 2) NOT NULL DEFAULT 0,
    gst_percentage NUMERIC(5, 2)  NOT NULL DEFAULT 0,
    amount         NUMERIC(14, 2) NOT NULL,
    gst_amount     NUMERIC(14, 2) NOT NULL,
    total_amount   NUMERIC(14, 2) NOT NULL
);
CREATE INDEX idx_soi_so ON sales_order_items (sales_order_id);
CREATE INDEX idx_soi_material ON sales_order_items (material_id);

CREATE TABLE customer_payments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_date     DATE           NOT NULL,
    customer_id      BIGINT         NOT NULL REFERENCES customers (id),
    sales_order_id   BIGINT         NOT NULL REFERENCES sales_orders (id),
    payment_mode     VARCHAR(20)    NOT NULL,
    amount_received  NUMERIC(14, 2) NOT NULL,
    reference_number VARCHAR(100),
    remarks          VARCHAR(500),
    advance          BOOLEAN        NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at       TIMESTAMP,
    created_by       VARCHAR(100),
    updated_by       VARCHAR(100),
    deleted          BOOLEAN        NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_cp_amount CHECK (amount_received > 0)
);
CREATE INDEX idx_cp_customer ON customer_payments (customer_id);
CREATE INDEX idx_cp_so ON customer_payments (sales_order_id);
CREATE INDEX idx_cp_date ON customer_payments (payment_date);

CREATE TABLE supplier_payments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_date      DATE           NOT NULL,
    supplier_id       BIGINT         NOT NULL REFERENCES suppliers (id),
    purchase_order_id BIGINT         NOT NULL REFERENCES purchase_orders (id),
    payment_mode      VARCHAR(20)    NOT NULL,
    amount_paid       NUMERIC(14, 2) NOT NULL,
    reference_number  VARCHAR(100),
    remarks           VARCHAR(500),
    created_at        TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at        TIMESTAMP,
    created_by        VARCHAR(100),
    updated_by        VARCHAR(100),
    deleted           BOOLEAN        NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_sp_amount CHECK (amount_paid > 0)
);
CREATE INDEX idx_sp_supplier ON supplier_payments (supplier_id);
CREATE INDEX idx_sp_po ON supplier_payments (purchase_order_id);
CREATE INDEX idx_sp_date ON supplier_payments (payment_date);

CREATE TABLE expenses (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_date            DATE           NOT NULL,
    expense_type            VARCHAR(30)    NOT NULL,
    amount                  NUMERIC(14, 2) NOT NULL,
    description             VARCHAR(500),
    attachment_name         VARCHAR(255),
    attachment_path         VARCHAR(500),
    attachment_content_type VARCHAR(100),
    created_at              TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at              TIMESTAMP,
    created_by              VARCHAR(100),
    updated_by              VARCHAR(100),
    deleted                 BOOLEAN        NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_exp_amount CHECK (amount > 0)
);
CREATE INDEX idx_exp_date ON expenses (expense_date);

CREATE TABLE customer_ledgers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT         NOT NULL REFERENCES customers (id),
    txn_date    DATE           NOT NULL,
    particular  VARCHAR(255)   NOT NULL,
    debit       NUMERIC(14, 2) NOT NULL DEFAULT 0,
    credit      NUMERIC(14, 2) NOT NULL DEFAULT 0,
    ref_type    VARCHAR(20)    NOT NULL,
    ref_id      BIGINT         NOT NULL,
    created_at  TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP,
    created_by  VARCHAR(100),
    updated_by  VARCHAR(100),
    deleted     BOOLEAN        NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_cl_customer_date ON customer_ledgers (customer_id, txn_date);
CREATE INDEX idx_cl_ref ON customer_ledgers (ref_type, ref_id);

CREATE TABLE supplier_ledgers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT         NOT NULL REFERENCES suppliers (id),
    txn_date    DATE           NOT NULL,
    particular  VARCHAR(255)   NOT NULL,
    debit       NUMERIC(14, 2) NOT NULL DEFAULT 0,
    credit      NUMERIC(14, 2) NOT NULL DEFAULT 0,
    ref_type    VARCHAR(20)    NOT NULL,
    ref_id      BIGINT         NOT NULL,
    created_at  TIMESTAMP      NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP,
    created_by  VARCHAR(100),
    updated_by  VARCHAR(100),
    deleted     BOOLEAN        NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_sl_supplier_date ON supplier_ledgers (supplier_id, txn_date);
CREATE INDEX idx_sl_ref ON supplier_ledgers (ref_type, ref_id);

CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(100),
    action      VARCHAR(50)  NOT NULL,
    entity_name VARCHAR(100),
    entity_id   VARCHAR(50),
    http_method VARCHAR(10),
    path        VARCHAR(300),
    status      VARCHAR(20),
    ip_address  VARCHAR(60),
    details     VARCHAR(1000),
    created_at  TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_created ON audit_logs (created_at);
CREATE INDEX idx_audit_user ON audit_logs (username);

